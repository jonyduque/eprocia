// Comando gerar escreve versao_embed.go com o carimbo dos arquivos em embed/.
// Rodado por go generate no diretório do pacote ocr.
package main

import (
	"fmt"
	"log"
	"os"

	"eprocia/internal/ocr/versao"
)

func main() {
	v, err := versao.Calcular(os.DirFS("."), "embed")
	if err != nil {
		log.Fatalf("falha ao calcular a versão dos embutidos: %v", err)
	}
	src := fmt.Sprintf(`// Code generated by go generate; DO NOT EDIT.

package ocr

// versaoEmbutidos identifica o conteúdo de embed/. Muda sempre que um binário
// ou modelo muda, e força a reextração na próxima execução.
const versaoEmbutidos = %q
`, v)
	if err := os.WriteFile("versao_embed.go", []byte(src), 0644); err != nil {
		log.Fatalf("falha ao gravar versao_embed.go: %v", err)
	}
}
